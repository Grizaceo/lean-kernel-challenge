#!/usr/bin/env python3
"""Generate an UNROLLED ca-rule110 init in the EXACT shape of the spec's
`encodeRow`, so that proving it correct is `rfl`-shaped rather than inductive.

Motivation (2026-09-27): the local instruction counter (scripts/icount.c) says
254 cells cost 2,768M instructions inside a structurally recursive `def`, while
a bare `caMix32` costs nothing. Lean compiles structural Nat recursion to
`brecOn`/`Nat.rec`, and the kernel must instantiate and type-check that at every
step. Two variants that only made the ARITHMETIC cheaper (incremental mix
argument, 32-bit byte lanes) moved the total 0.8% and 0.5% -- confirming the
arithmetic is not the target. Unrolling removes the loop and cost 9.9x.

The spec encodes the row as

    encodeRow row = row.foldr (fun b acc => 2 * acc + (if b then 1 else 0)) 0

so cell `i` lands at bit `i`. Unrolling THAT foldr into a nested expression
keeps every arithmetic step the kernel was already doing, removes only the
recursion, and makes

    initUnrolled seed = encodeRow (initRowFor seed)

provable by unfolding both sides to the same nested term, instead of needing
v2's ~100-line simultaneous `testBit` induction.

Cells 0 and 1 are fixed by the spec (true, false) and are emitted as the
constant leaves rather than passed through the mixer.

    python3 gen_unrolled_init.py > InitAB2.lean
"""
import sys

K = 0x9e3779b9
W = 256
IND = " " * 2


def bit_expr(c: int) -> str:
    """The Nat term for cell `c`: the spec's mix, shifted to its natural bit."""
    if c == 0:
        return "1"
    if c == 1:
        return "0"
    return ("(if (caMix32 (seed + %d * 0x%09x)).testBit 31 then 1 else 0)" % (c + 1, K))


def emit() -> str:
    out = []
    w = out.append
    w("/-!")
    w("GENERATED by scripts/gen_unrolled_init.py -- do not edit by hand.")
    w("")
    w("A/B harness (NOT a submission): the ca-rule110 initial row, unrolled and")
    w("in the exact shape of the spec's `encodeRow` foldr, so the value matches")
    w("`encodeRow (initRowFor seed)` by unfolding rather than by induction.")
    w("")
    w("  initUnrolled -- the full 256-cell foldr, nested, no recursion")
    w("  initLanes    -- eight flat 32-cell lanes combined once")
    w("-/")
    w("")
    w("-- The unrolled foldr is 256 levels deep by construction; without these the")
    w("-- elaborator's heartbeat budget runs out in the LCNF compiler before the")
    w("-- term is ever type-checked. (They must sit AFTER the docstring above --")
    w("-- inside it they are just comment text.)")
    w("set_option maxRecDepth 1000000")
    w("set_option maxHeartbeats 0")
    w("")
    w("namespace InitAB2")
    w("")
    w("def ruleWidth : Nat := %d" % W)
    w("")
    w("/-- Verbatim from problems/ca-rule110/Spec.lean. -/")
    w("def caMix32 (x : Nat) : Nat :=")
    w("  let x := ((x ^^^ (x >>> 16)) * 0x7feb352d) &&& 0xffffffff")
    w("  let x := ((x ^^^ (x >>> 15)) * 0x846ca68b) &&& 0xffffffff")
    w("  (x ^^^ (x >>> 16)) &&& 0xffffffff")
    w("")

    # --- initUnrolled: nest the foldr exactly -------------------------------
    # foldr g 0 [b0 .. b255] = 2 * (2 * (... (2 * b255 + b254) ...) + b1) + b0
    w("/-! ### unrolled foldr, cell i at bit i -/")
    w("")
    w("def initUnrolled (seed : Nat) : Nat :=")
    # Start from the spec's own seed of the foldr. `foldr g 0` bottoms out at
    # `2 * 0 + b255`, NOT at `b255`; matching that literally is what makes the
    # two terms syntactically equal instead of merely extensionally so.
    term = "2 * 0 + %s" % bit_expr(W - 1)
    for c in range(W - 2, -1, -1):
        # parens are load-bearing: without them `2 * %s` re-associates to the
        # left and produces a 256-long `2 * 2 * ... * 2 * bit` product, which
        # the LCNF compiler cannot get through.
        term = "2 * (%s) + %s" % (term, bit_expr(c))
    # emit wrapped so no line runs away
    line = IND
    depth = 0
    for tok in term.split(" "):
        if len(line) + len(tok) > 76:
            w(line)
            line = IND
        line += tok + " "
    if line.strip():
        w(line.rstrip())
    w("")

    # --- initLanes: eight flat 32-cell lanes -------------------------------
    w("/-! ### eight flat lanes of 32 cells, combined once -/")
    w("")
    for l in range(8):
        lo = W - 32 * (l + 1)
        hi = W - 32 * l - 1
        w("/-- Lane %d: cells %d..%d, returned with cell %d at bit 0. -/"
          % (l, lo, hi, lo))
        w("def lane%d (seed : Nat) : Nat :=" % l)
        seg = []
        for c in range(hi, lo - 1, -1):
            seg.append("  " + bit_expr(c))
        w("\n  +\n".join(seg) if len(seg) > 1 else seg[0])
        w("")

    w("/-- Lane values are placed at their natural bit offsets; the cells are")
    w("disjoint, so `|||` and `+` agree here. Lane 7 covers cells 0..31 and")
    w("already carries the fixed first two cells. -/")
    w("def initLanes (seed : Nat) : Nat :=")
    terms = []
    for l in range(8):
        lo = W - 32 * (l + 1)
        terms.append("(lane%d seed <<< %d)" % (l, lo) if lo else "(lane7 seed)")
    w("  " + " |||\n  ".join(terms))
    w("")
    w("end InitAB2")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(emit())
