#!/usr/bin/env python3
"""Generate an UNROLLED ca-rule110 init, to test whether the cost lives in the
kernel's structural-recursion machinery rather than in the arithmetic.

Motivation (2026-09-27): the local instruction counter says 254 cells cost
2,769M instructions (~10.9M each) while a bare `caMix32` call costs under 2M.
That is not additive, so the cost is not "per mix" -- it is per ITERATION of
whatever loop carries the cells. The shipped v2 init carries them with a
structurally recursive `def`, and Lean's structural Nat recursion elaborates to
`brecOn`/`Nat.rec`, which the kernel must instantiate and type-check at every
step. Two cheaper-arithmetic variants (incremental mix argument; 32-bit byte
lanes) moved the total by 0.8% and 0.5% -- i.e. the arithmetic is not the
target, the iteration is.

This emits the same value with NO recursion at all: one flat expression whose
254 terms are `bit <<< i`, associated to the right so no loop is needed.

    python3 gen_unrolled_init.py > InitAB2.lean
"""
import sys

K = 0x9e3779b9
W = 256


def cell_terms():
    """(shift, mix_arg) for every cell that needs the mixer: 2..255."""
    for c in range(2, W):
        # Spec: cell c is (caMix32 (seed + (c + 1) * K)).testBit 31
        yield c, c + 1


def emit():
    out = []
    out.append("/-!")
    out.append("GENERATED by scripts/gen_unrolled_init.py -- do not edit by hand.")
    out.append("")
    out.append("A/B harness (NOT a submission): the ca-rule110 initial row with NO")
    out.append("recursion, to test whether the init cost lives in the kernel's")
    out.append("structural-recursion machinery rather than in the arithmetic.")
    out.append("")
    out.append("  initBits5 -- flat, right-associated: 254 `bit <<< i` terms + 1")
    out.append("  initBits6 -- eight flat 32-term lanes combined once")
    out.append("-/")
    out.append("")
    out.append("namespace InitAB2")
    out.append("")
    out.append("def ruleWidth : Nat := %d" % W)
    out.append("")
    out.append("/-- Verbatim from problems/ca-rule110/Spec.lean. -/")
    out.append("def caMix32 (x : Nat) : Nat :=")
    out.append("  let x := ((x ^^^ (x >>> 16)) * 0x7feb352d) &&& 0xffffffff")
    out.append("  let x := ((x ^^^ (x >>> 15)) * 0x846ca68b) &&& 0xffffffff")
    out.append("  (x ^^^ (x >>> 16)) &&& 0xffffffff")
    out.append("")
    out.append("/-- One cell as a Nat: the mix bit at its natural position. -/")
    out.append("def cell (seed : Nat) (arg i : Nat) : Nat :=")
    out.append("  (if (caMix32 (seed + arg * 0x%09x)).testBit 31 then 1 else 0) <<< i" % K)
    out.append("")
    out.append("/-! ### flat, fully unrolled -/")
    out.append("")
    out.append("def initBits5 (seed : Nat) : Nat :=")
    lines = []
    for c, a in cell_terms():
        lines.append("  (if (caMix32 (seed + %d * 0x%09x)).testBit 31 then 1 else 0) <<< %d"
                     % (a, K, c))
    # right-associated: `a ||| b ||| c` in Lean is right-assoc by default
    body = " |||\n".join(lines)
    out.append(body)
    out.append("  ||| 1")
    out.append("")
    out.append("/-! ### eight flat lanes of 32, combined once -/")
    out.append("")
    for l in range(8):
        out.append("def lane%d (seed : Nat) : Nat :=" % l)
        lo = 256 - 32 * (l + 1)
        hi = 255 - 32 * l
        seg = []
        for c in range(max(lo, 2), hi + 1):
            seg.append("  (if (caMix32 (seed + %d * 0x%09x)).testBit 31 then 1 else 0) <<< %d"
                       % (c + 1, K, c - lo))
        if not seg:
            seg = ["  0"]
        out.append(" |||\n".join(seg))
        out.append("")
    out.append("def initBits6 (seed : Nat) : Nat :=")
    out.append("  ((lane0 seed <<< 224) ||| (lane1 seed <<< 192) |||")
    out.append("   (lane2 seed <<< 160) ||| (lane3 seed <<< 128) |||")
    out.append("   (lane4 seed <<< 96) ||| (lane5 seed <<< 64) |||")
    out.append("   (lane6 seed <<< 32) ||| (lane7 seed <<< 2)) ||| 1")
    out.append("")
    out.append("end InitAB2")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(emit())
